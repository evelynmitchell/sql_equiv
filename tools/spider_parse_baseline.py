#!/usr/bin/env python3
"""
Spider parse-rate baseline (north-star metric).

Runs the Spider dev-set queries (benchmarks/spider/dev_queries.sql) through
the sql_equiv parser via `sql_equiv --parse-lines` and reports the parse rate,
with failures grouped into classes — each failure class is a candidate issue.

The passing count is ratcheted in tools/spider_parse_minimum.txt: CI fails if
it regresses. When the parser improves, run with --update-ratchet.

Usage:
    python3 tools/spider_parse_baseline.py            # report + ratchet check
    python3 tools/spider_parse_baseline.py --check    # ratchet check only (CI)
    python3 tools/spider_parse_baseline.py --update-ratchet

Stdlib only (CI runs plain python3).
"""

from __future__ import annotations

import re
import subprocess
import sys
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
QUERIES = ROOT / "benchmarks" / "spider" / "dev_queries.sql"
REPORT = ROOT / "benchmarks" / "spider" / "parse_report.md"
RATCHET = ROOT / "tools" / "spider_parse_minimum.txt"
EXE = ROOT / ".lake" / "build" / "bin" / "sql_equiv"


def classify(msg: str) -> str:
    """Group parse error messages into failure classes (issue candidates)."""
    m = re.sub(r"at line \d+, column \d+:? ?", "", msg)
    m = re.sub(r"\s*near .*$", "", m)        # drop source context
    # "Unexpected character: 'X'" — the character IS the class
    cm = re.search(r"Unexpected character: '(.)'", m)
    if cm:
        return f"Unexpected character {cm.group(1)!r}"
    km = re.search(
        r"(Unexpected keyword \w+|Expected [\w'\(\)]+|[Uu]nsupported \w+|Unknown \w+|Unexpected token \S+)", m)
    if km:
        return km.group(1)
    m = re.sub(r"'[^']*'", "'_'", m)          # literal contents last
    return m[:60]


def run() -> tuple[int, int, dict[str, list[tuple[int, str]]]]:
    if not EXE.exists():
        sys.exit(f"error: {EXE} not built — run `lake build sql_equiv` first")
    queries = QUERIES.read_text().splitlines()
    out = subprocess.run(
        [str(EXE), "--dialect", "sqlite", "--parse-lines", str(QUERIES)],
        capture_output=True, text=True, check=True,
    ).stdout
    ok, failures = 0, defaultdict(list)
    total = 0
    for line in out.splitlines():
        parts = line.split("\t")
        if parts[0] == "ok":
            ok += 1
            total += 1
        elif parts[0] == "err":
            total += 1
            lineno = int(parts[1])
            msg = parts[2] if len(parts) > 2 else "(no message)"
            failures[classify(msg)].append((lineno, queries[lineno - 1]))
    return ok, total, failures


def write_report(ok: int, total: int, failures: dict) -> None:
    rate = 100.0 * ok / total if total else 0.0
    lines = [
        "# Spider Dev-Set Parse Report",
        "",
        "Generated by `tools/spider_parse_baseline.py` — do not edit by hand.",
        "",
        f"**Parse rate: {ok}/{total} unique queries ({rate:.1f}%)**",
        "",
        "Corpus: `dev_queries.sql` — unique queries from the Spider dev set",
        "([taoyds/spider](https://github.com/taoyds/spider), CC BY-SA 4.0).",
        "Parsed in the `sqlite` dialect, since Spider's gold results come from sqlite",
        "(`docs/IMPLEMENTATION_DEFINED.md`).",
        "",
        "## Failure classes (each is an issue candidate, largest first)",
        "",
        "| Count | Class | Example (first occurrence) |",
        "|------:|-------|----------------------------|",
    ]
    for cls, items in sorted(failures.items(), key=lambda kv: -len(kv[1])):
        example = items[0][1]
        example = (example[:90] + "…") if len(example) > 90 else example
        lines.append(f"| {len(items)} | {cls} | `{example}` |")
    REPORT.write_text("\n".join(lines) + "\n")


def main() -> None:
    check_only = "--check" in sys.argv
    update = "--update-ratchet" in sys.argv
    ok, total, failures = run()
    if not check_only:
        write_report(ok, total, failures)
        print(f"Parse rate: {ok}/{total} ({100.0 * ok / total:.1f}%) — report: {REPORT}")
    minimum = int(RATCHET.read_text().strip()) if RATCHET.exists() else 0
    if update or not RATCHET.exists():
        RATCHET.write_text(f"{ok}\n")
        print(f"Ratchet set to {ok}")
        return
    if ok < minimum:
        sys.exit(f"FAIL: Spider parse count regressed: {ok} < ratchet {minimum}")
    print(f"Ratchet check passed: {ok} >= {minimum}")


if __name__ == "__main__":
    main()
