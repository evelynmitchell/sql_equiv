#!/usr/bin/env bash
# Writes docbuild/SqlEquivDocs.lean, the root module the API docs are built from: it imports the
# three libraries, so doc-gen4 documents every module they contain. SqlBridge has no root module of
# its own (it is declared by globs), so its modules are listed from the files on disk; modules that
# define a top-level `main` (the executables' entry points) are left out, as two would clash.
set -euo pipefail
cd "$(dirname "$0")/.."
{
  echo "-- Generated by docbuild/mkroot.sh: do not edit."
  echo "import SqlEquiv"
  echo "import SqlCore"
  for f in SqlBridge/*.lean; do
    grep -qE '^(unsafe |partial )?def main\b' "$f" && continue
    m="${f%.lean}"
    echo "import ${m//\//.}"
  done
} > docbuild/SqlEquivDocs.lean
